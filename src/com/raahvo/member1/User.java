package com.raahvo.member1;

import java.time.LocalDateTime;

/**
 * ============================================================================
 * RAAHVO - Smart Travel Booking & Trip Planning System
 * Module: Member 1 - User & Destination Management
 * ============================================================================
 * Class: User
 * Course Concept: Encapsulation (OOP)
 * 
 * Purpose:
 * Encapsulates personal and account credentials of travelers and administrators.
 * Demonstrates data hiding via private attributes and controlled public getters/setters.
 */
public class User {
    // Unique identifier for the user (auto-generated by DB or ID generator)
    private int userId;
    
    // User's full display name
    private String name;
    
    // Unique email address used as login username
    private String email;
    
    // 10-digit primary mobile contact number
    private String phone;
    
    // Credential hash (never stored in plain text in production)
    private String passwordHash;
    
    // System authorization role: "CUSTOMER" or "ADMIN"
    private String role;
    
    // Account creation audit timestamp
    private LocalDateTime createdAt;

    /**
     * Parameterized Constructor for new user registration
     * Defaults role to "CUSTOMER" if not specified.
     */
    public User(int userId, String name, String email, String phone, String passwordHash, String role) {
        this.userId = userId;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.passwordHash = passwordHash;
        // Business Rule: Ensure default role is CUSTOMER if input is null or blank
        this.role = (role == null || role.trim().isEmpty()) ? "CUSTOMER" : role.toUpperCase();
        this.createdAt = LocalDateTime.now();
    }

    /**
     * Overloaded Constructor for restoring users from persistent database records
     */
    public User(int userId, String name, String email, String phone, String passwordHash, String role, LocalDateTime createdAt) {
        this.userId = userId;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.passwordHash = passwordHash;
        this.role = role;
        this.createdAt = createdAt;
    }

    // ========================================================================
    // GETTERS AND SETTERS (Demonstrating Encapsulation & Defensive Access)
    // ========================================================================

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public void setPasswordHash(String passwordHash) {
        this.passwordHash = passwordHash;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    /**
     * Helper authorization method to check if this user has admin rights
     * @return true if role is ADMIN, false otherwise
     */
    public boolean isAdmin() {
        return "ADMIN".equalsIgnoreCase(this.role);
    }

    /**
     * String representation of user object for logging & debugging
     * Note: passwordHash is deliberately omitted for security reasons!
     */
    @Override
    public String toString() {
        return String.format("User[ID=%d, Name='%s', Email='%s', Role='%s']", userId, name, email, role);
    }
}
