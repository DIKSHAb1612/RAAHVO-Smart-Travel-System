package com.raahvo.member1;

import com.raahvo.common.ConsoleUI;
import com.raahvo.common.DatabaseConnection;
import com.raahvo.common.InMemoryDatabase;
import com.raahvo.exception.AuthenticationException;
import com.raahvo.exception.CustomException;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

/**
 * ============================================================================
 * RAAHVO - Smart Travel Booking & Trip Planning System
 * Module: Member 1 - User & Destination Management
 * ============================================================================
 * Class: Registration
 * Course Concepts:
 * - Collections (HashSet for O(1) duplicate email detection)
 * - Custom Exceptions (AuthenticationException)
 * - JDBC (PreparedStatement and auto-generated keys)
 * 
 * Purpose:
 * Handles sign-up validation, format verification, duplicate collision checks,
 * and persistent storage of newly created customer accounts.
 */
public class Registration {
    private final InMemoryDatabase inMemoryDb;
    private final DatabaseConnection dbConn;

    public Registration() {
        this.inMemoryDb = InMemoryDatabase.getInstance();
        this.dbConn = DatabaseConnection.getInstance();
    }

    /**
     * Registers a new customer into the system
     * 
     * @param name Full display name
     * @param email Unique email address (case-insensitive)
     * @param phone 10-digit mobile number
     * @param password Password (min 6 characters)
     * @return Newly registered User entity
     * @throws AuthenticationException if validation fails or email already exists
     */
    public User registerUser(String name, String email, String phone, String password) throws AuthenticationException {
        // Step 1: Input Validation checks
        if (name == null || name.trim().isEmpty()) {
            throw new AuthenticationException("Full name cannot be blank.");
        }
        if (email == null || !email.contains("@")) {
            throw new AuthenticationException("Invalid email address provided.");
        }
        if (phone == null || phone.length() < 10) {
            throw new AuthenticationException("Phone number must have at least 10 digits.");
        }
        if (password == null || password.length() < 6) {
            throw new AuthenticationException("Password must be at least 6 characters long.");
        }

        // Normalize email to lowercase for consistent uniqueness checking
        String normalizedEmail = email.trim().toLowerCase();

        // Step 2: Course Concept -> HashSet O(1) duplicate lookup
        // Prevents iterating through the whole database to find duplicate emails
        if (inMemoryDb.registeredEmails.contains(normalizedEmail)) {
            throw new AuthenticationException("An account with email '" + normalizedEmail + "' already exists!");
        }

        // Step 3: Course Concept -> JDBC PreparedStatement with parameterized query
        int newUserId = inMemoryDb.userIdGen.getAndIncrement();
        if (dbConn.isSqlServerConnected()) {
            String sql = "INSERT INTO Users (name, email, phone, password_hash, role) VALUES (?, ?, ?, ?, 'CUSTOMER');";
            try (Connection conn = dbConn.getConnection();
                 PreparedStatement stmt = conn.prepareStatement(sql, PreparedStatement.RETURN_GENERATED_KEYS)) {
                
                // Using positional parameters to prevent SQL Injection
                stmt.setString(1, name);
                stmt.setString(2, normalizedEmail);
                stmt.setString(3, phone);
                stmt.setString(4, password);
                stmt.executeUpdate();
                
                // Retrieve auto-increment IDENTITY key generated by SQL Server
                try (ResultSet rs = stmt.getGeneratedKeys()) {
                    if (rs.next()) {
                        newUserId = rs.getInt(1);
                    }
                }
            } catch (SQLException e) {
                ConsoleUI.printWarning("SQL Server insert error: " + e.getMessage() + ". Registering in memory store.");
            }
        }

        // Step 4: Synchronize In-Memory Cache for fast runtime lookups
        User newUser = new User(newUserId, name, normalizedEmail, phone, password, "CUSTOMER");
        inMemoryDb.users.put(newUser.getUserId(), newUser);
        inMemoryDb.registeredEmails.add(normalizedEmail);

        return newUser;
    }

    /**
     * Updates user contact details
     */
    public boolean updateProfile(int userId, String newName, String newPhone) throws CustomException {
        User user = inMemoryDb.users.get(userId);
        if (user == null) {
            throw new CustomException("USER_NOT_FOUND", "User ID not found in system.");
        }

        user.setName(newName);
        user.setPhone(newPhone);

        if (dbConn.isSqlServerConnected()) {
            String sql = "UPDATE Users SET name = ?, phone = ? WHERE user_id = ?;";
            try (Connection conn = dbConn.getConnection();
                 PreparedStatement stmt = conn.prepareStatement(sql)) {
                stmt.setString(1, newName);
                stmt.setString(2, newPhone);
                stmt.setInt(3, userId);
                stmt.executeUpdate();
            } catch (SQLException e) {
                System.err.println("Database sync warning: " + e.getMessage());
            }
        }
        return true;
    }

    /**
     * Updates user password with old credential verification
     */
    public boolean changePassword(int userId, String oldPassword, String newPassword) throws CustomException {
        User user = inMemoryDb.users.get(userId);
        if (user == null) {
            throw new CustomException("USER_NOT_FOUND", "User ID not found.");
        }
        if (!user.getPasswordHash().equals(oldPassword)) {
            throw new CustomException("INVALID_CREDENTIALS", "Current password does not match.");
        }
        if (newPassword.length() < 6) {
            throw new CustomException("WEAK_PASSWORD", "New password must be at least 6 characters.");
        }

        user.setPasswordHash(newPassword);

        if (dbConn.isSqlServerConnected()) {
            String sql = "UPDATE Users SET password_hash = ? WHERE user_id = ?;";
            try (Connection conn = dbConn.getConnection();
                 PreparedStatement stmt = conn.prepareStatement(sql)) {
                stmt.setString(1, newPassword);
                stmt.setInt(2, userId);
                stmt.executeUpdate();
            } catch (SQLException e) {
                System.err.println("Database sync warning: " + e.getMessage());
            }
        }
        return true;
    }

    /**
     * Retrieves all registered users for Admin panel audit
     */
    public List<User> getAllUsers() {
        return new ArrayList<>(inMemoryDb.users.values());
    }

    /**
     * Checks if an email is already registered in the system (case-insensitive)
     */
    public boolean isEmailRegistered(String email) {
        if (email == null) return false;
        return inMemoryDb.registeredEmails.contains(email.trim().toLowerCase());
    }
}
